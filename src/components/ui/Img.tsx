"use client";

import type { CSSProperties } from "react";
import manifest from "@/content/media.generated.json";
import { asset } from "@/lib/asset";

type Entry = { w: number; h: number; widths: number[] };
const media = manifest as Record<string, Entry>;

/** Intrinsic size of a public image (from the build manifest). */
export function mediaSize(src: string) {
  const m = media[src];
  return m ? { width: m.w, height: m.h } : null;
}

const variant = (src: string, w: number) => asset(`/img${src.replace(/\.[a-z]+$/i, "")}-${w}.webp`);

/**
 * Static-export image (pack 12 + 15.1 §6): WebP srcset pre-generated by scripts/optimize-images.mjs,
 * intrinsic width/height from the manifest (no CLS), lazy by default, `priority` only for the hero.
 */
export function Img({
  src,
  alt,
  sizes = "100vw",
  className,
  style,
  priority = false,
  eager = false,
  draggable,
  ...rest
}: {
  src: string;
  alt: string;
  sizes?: string;
  className?: string;
  style?: CSSProperties;
  priority?: boolean;
  eager?: boolean;
  draggable?: boolean;
  "aria-hidden"?: boolean;
}) {
  const m = media[src];
  if (!m) {
    // eslint-disable-next-line @next/next/no-img-element
    return <img src={asset(src)} alt={alt} className={className} style={style} loading={priority || eager ? "eager" : "lazy"} decoding="async" draggable={draggable} {...rest} />;
  }
  const srcSet = m.widths.map((w) => `${variant(src, w)} ${w}w`).join(", ");
  const fallbackW = m.widths.filter((w) => w <= 1080).pop() ?? m.widths[0];
  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={variant(src, fallbackW)}
      srcSet={srcSet}
      sizes={sizes}
      width={m.w}
      height={m.h}
      alt={alt}
      className={className}
      style={style}
      loading={priority || eager ? "eager" : "lazy"}
      fetchPriority={priority ? "high" : undefined}
      decoding={priority ? "sync" : "async"}
      onError={(event) => {
        // If a browser cannot fetch a generated responsive variant, retry the
        // original public image once instead of leaving the Team photo blank.
        const img = event.currentTarget;
        if (img.dataset.fallbackOriginal) return;
        img.dataset.fallbackOriginal = "1";
        img.removeAttribute("srcset");
        img.src = asset(src);
      }}
      draggable={draggable}
      {...rest}
    />
  );
}
