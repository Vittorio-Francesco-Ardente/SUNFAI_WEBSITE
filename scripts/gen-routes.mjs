#!/usr/bin/env node
/**
 * Generates the thin route wrappers for both locales (pack 14.1):
 *   src/app/(it)/<path>/page.tsx            → <View locale="it" />
 *   src/app/(lmo)/bergamasch/<path>/page.tsx → <View locale="lmo" />
 * Page components live in src/views/*. Re-run after adding a route: `node scripts/gen-routes.mjs`.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = path.join(process.cwd(), "src", "app");

/** [route folder, view module, export prefix, dynamic param?] */
const routes = [
  ["", "home", "Home"],
  ["chi-siamo", "chi-siamo", "ChiSiamo"],
  ["cosa-facciamo", "cosa-facciamo", "CosaFacciamo"],
  ["team", "team", "Team"],
  ["team/[slug]", "team-member", "Member", "slug"],
  ["le-cer", "le-cer", "LeCer"],
  ["riconoscimenti", "riconoscimenti", "Riconoscimenti"],
  ["notizie", "notizie", "Notizie"],
  ["notizie/[slug]", "article", "Article", "slug"],
  ["eventi", "eventi", "Eventi"],
  ["eventi/[slug]", "evento", "Evento", "slug"],
  ["ardake", "ardake", "Ardake"],
  ["ardake/monitoraggio", "monitoraggio", "Monitoraggio"],
  ["ardake/demo", "ardake-demo", "ArdakeDemo"],
  ["ardake/[cabina]", "cabina-redirect", "Cabina", "cabina"],
  ["diventa-socio", "diventa-socio", "DiventaSocio"],
  ["diventa-socio/compilazione", "compilazione", "Compilazione"],
  ["diventa-socio/grazie", "grazie", "Grazie"],
  ["contatti", "contatti", "Contatti"],
  ["note-legali", "note-legali", "NoteLegali"],
  ["dev/styleguide", "dev-styleguide", "Styleguide"],
  ["dev/bergamasco", "dev-bergamasco", "Bergamasco"],
  ["dev/style-lab", "dev-style-lab", "StyleLab"],
];

const header = "// GENERATED by scripts/gen-routes.mjs — edit the view in src/views instead.\n";

for (const locale of ["it", "lmo"]) {
  const base = locale === "it" ? path.join(ROOT, "(it)") : path.join(ROOT, "(lmo)", "bergamasch");
  for (const [route, view, name, param] of routes) {
    const dir = path.join(base, ...route.split("/").filter(Boolean));
    fs.mkdirSync(dir, { recursive: true });
    let src;
    if (param) {
      src = `${header}import { ${name}Page, ${name.toLowerCase()}Meta, ${name.toLowerCase()}Params } from "@/views/${view}";

export const dynamicParams = false;
export const generateStaticParams = ${name.toLowerCase()}Params;

export async function generateMetadata({ params }: { params: Promise<{ ${param}: string }> }) {
  const { ${param} } = await params;
  return ${name.toLowerCase()}Meta("${locale}", ${param});
}

export default async function Page({ params }: { params: Promise<{ ${param}: string }> }) {
  const { ${param} } = await params;
  return <${name}Page locale="${locale}" ${param}={${param}} />;
}
`;
    } else {
      src = `${header}import { ${name}Page, ${name.toLowerCase()}Meta } from "@/views/${view}";

export const generateMetadata = () => ${name.toLowerCase()}Meta("${locale}");

export default function Page() {
  return <${name}Page locale="${locale}" />;
}
`;
    }
    fs.writeFileSync(path.join(dir, "page.tsx"), src);
  }
}
console.log(`[routes] ${routes.length} routes × 2 locales written`);
